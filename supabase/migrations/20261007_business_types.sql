-- Applied to the Supabase project on 7.10.2026 (the aliases were loaded there
-- from the cleanup backup; the explicit list below is the same 268 pairs).
-- Closed list of business types, kept in the database so it grows by itself.
-- Whatever writes a business — manual entry, an edit, the agent's upload
-- (relay, workflow or any future path) — goes through the trigger below:
--   * a known variant is rewritten to its list entry (business_type_aliases);
--   * a type not on the list is added to it, marked with who brought it.
-- So the list stays closed (every business.type is on it) yet never blocks a
-- new kind of business.

create table if not exists public.business_types (
  name       text primary key check (btrim(name) <> ''),
  source     text not null default 'initial' check (source in ('initial', 'employee', 'agent')),
  created_at timestamptz not null default now()
);

create table if not exists public.business_type_aliases (
  alias     text primary key,
  type_name text not null references public.business_types(name) on update cascade
);

alter table public.business_types enable row level security;
alter table public.business_type_aliases enable row level security;
drop policy if exists authenticated_full_access on public.business_types;
create policy authenticated_full_access on public.business_types
  for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');
drop policy if exists authenticated_full_access on public.business_type_aliases;
create policy authenticated_full_access on public.business_type_aliases
  for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');

