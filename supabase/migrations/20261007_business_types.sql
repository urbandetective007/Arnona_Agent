create or replace function public.normalize_business_type()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  raw    text := btrim(coalesce(new.type, ''));
  mapped text;
begin
  if raw = '' then
    new.type := '';
    return new;
  end if;
  select type_name into mapped from business_type_aliases
   where alias = raw or alias = btrim(replace(raw, '✅', ''))
   limit 1;
  if mapped is not null then
    new.type := mapped;
    return new;
  end if;
  new.type := btrim(replace(raw, '✅', ''));
  insert into business_types (name, source)
  values (new.type, case when new.source = 'manual' then 'employee' else 'agent' end)
  on conflict (name) do nothing;
  return new;
end;
$$;

drop trigger if exists businesses_normalize_type on public.businesses;
create trigger businesses_normalize_type
  before insert or update of type on public.businesses
  for each row execute function public.normalize_business_type();
